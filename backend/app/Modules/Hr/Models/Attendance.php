<?php

namespace App\Modules\Hr\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\SoftDeletes;

class Attendance extends Model
{
    /**
     * The statuses HR may set on a day (Slice 16). Each one has a defined pay meaning in
     * AttendanceService::unpaidDaysDetailFor() — adding a value here without teaching that loop
     * about it would give HR a control that silently does nothing:
     *
     *   present    paid, no deduction
     *   late       paid; counts toward the late tally and per-minute charge
     *   absent     one unpaid day
     *   on_leave   follows the covering leave request; paid when there is none
     *   half_day   half an unpaid day
     *   rest_day   not a working day — never unpaid
     *   holiday    paid, no deduction
     */
    public const HR_STATUSES = ['present', 'late', 'absent', 'on_leave', 'half_day', 'rest_day', 'holiday'];

    /** Statuses that mean the day is fully paid and raises no violation. */
    public const PAID_STATUSES = ['present', 'late', 'on_leave', 'rest_day', 'holiday'];

    use SoftDeletes;

    protected $table = 'hr_attendance';

    /** A human put this row here — the employee clocked in, or HR entered/corrected it. */
    public const SOURCE_MANUAL = 'manual';

    /** Generated by the platform (the nightly management-attendance job). */
    public const SOURCE_SYSTEM = 'system';

    /**
     * How a clock-in proved where the employee was (`location_verified_by`). NULL — the
     * default — means no check ran at all: the feature was off, the row predates it, or the
     * policy was enabled but unconfigured and failed open. Only these three values assert
     * that something was actually verified.
     */
    /** On the office network AND inside the fence, on a fix worth trusting. */
    public const LOCATION_IP_GPS = 'ip_gps';

    /** On the office network; no usable GPS fix (typically an ethernet desktop). */
    public const LOCATION_IP_ONLY = 'ip_only';

    /** Off-site selfie, approved by a human. HR's eyes ARE the verification. */
    public const LOCATION_REMOTE_APPROVED = 'remote_approved';

    protected $fillable = [
        'employee_id',
        'work_date',
        'time_in',
        'time_out',
        'lunch_started_at',
        'break_started_at',
        'lunch_minutes',
        'break_minutes',
        'hours_worked',
        'status',
        // Slice 16 — a human asserted this status; derivation must not overwrite it.
        'status_override',
        'leave_credit_refunded_at',
        'note',
        'source',
        'location_verified_by',
        'tasks',
    ];

    protected $casts = [
        'work_date' => 'date',
        'status_override' => 'boolean',
        'leave_credit_refunded_at' => 'datetime',
        'time_in' => 'datetime',
        'time_out' => 'datetime',
        'lunch_started_at' => 'datetime',
        'break_started_at' => 'datetime',
        'lunch_minutes' => 'integer',
        'break_minutes' => 'integer',
        'hours_worked' => 'decimal:2',
        'tasks' => 'array',
    ];

    /**
     * The employee this belongs to — `withTrashed()` because a SEPARATION SOFT-DELETES THEM.
     *
     * Without it the default scope resolves this to null the moment somebody leaves, and every
     * Resource that reads a name through it throws, taking the whole list endpoint down with it —
     * one 500 for the entire page because one row belonged to a leaver. Their history does not
     * stop being theirs when they go, and a record that cannot say whose it is is worse than one
     * that names someone who has left.
     */
    public function employee(): BelongsTo
    {
        return $this->belongsTo(Employee::class)->withTrashed();
    }

    /** True when the platform generated this row rather than a person. */
    public function isSystemGenerated(): bool
    {
        return $this->source === self::SOURCE_SYSTEM;
    }

    /** Derived clock state the UI uses to decide which buttons to show. */
    public function getStateAttribute(): string
    {
        return match (true) {
            $this->time_out !== null => 'clocked_out',
            $this->lunch_started_at !== null => 'on_lunch',
            $this->break_started_at !== null => 'on_break',
            $this->time_in !== null => 'clocked_in',
            default => 'not_clocked_in',
        };
    }
}
